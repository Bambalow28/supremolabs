/// Segmented like the grid above: lit blocks to the value, unlit track after.
class _BarPainter extends CustomPainter {
  final double v;
  final Color color;
  _BarPainter(this.v, this.color);

  @override
  void paint(Canvas canvas, Size size) {
    const n = 48;
    const gap = 2.0;
    final w = (size.width - gap * (n - 1)) / n;
    final on = (v * n).ceil();
    for (var i = 0; i < n; i++) {
      final r = RRect.fromRectAndRadius(
        Rect.fromLTWH(i * (w + gap), 0, w, size.height),
        const Radius.circular(2),
      );
      if (i < on) {
        canvas.drawRRect(
          r,
          Paint()..color = color.withValues(alpha: 0.35 + 0.65 * (i / n)),
        );
      } else {
        canvas.drawRRect(
          r,
          Paint()..color = Colors.white.withValues(alpha: 0.06),
        );
      }
    }
  }

  @override
  bool shouldRepaint(_BarPainter old) => old.v != v || old.color != color;
}

