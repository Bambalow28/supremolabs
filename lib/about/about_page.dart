/// A number that counts up when it scrolls into view.
class _Count extends StatelessWidget {
  final int value;
  final TextStyle style;
  const _Count(this.value, {required this.style});

  @override
  Widget build(BuildContext context) {
    final reduce = MediaQuery.disableAnimationsOf(context);
    return WhenVisible(
      builder: (context, visible) => TweenAnimationBuilder<double>(
        tween: Tween(
          begin: reduce ? value.toDouble() : 0,
          end: visible ? value.toDouble() : (reduce ? value.toDouble() : 0),
        ),
        duration: const Duration(milliseconds: 1600),
        curve: const Cubic(0.16, 1, 0.3, 1),
        builder: (_, v, _) => Text('${v.round()}', style: style),
      ),
    );
  }
}

const _weeks = 53;
const _gap = 3.0;

class _CommitGrid extends StatefulWidget {
  const _CommitGrid();

  @override
  State<_CommitGrid> createState() => _CommitGridState();
}

class _CommitGridState extends State<_CommitGrid>
    with SingleTickerProviderStateMixin {
  late final _c = AnimationController(
    vsync: this,
    duration: const Duration(milliseconds: 2200),
  );
  final _scroll = ScrollController();
  int? _hover; // week * 7 + day

  @override
  void dispose() {
    _c.dispose();
    _scroll.dispose();
    super.dispose();
  }

  DateTime _date(int i) => activityStart.add(Duration(days: i));

  @override
  Widget build(BuildContext context) {
    final reduce = MediaQuery.disableAnimationsOf(context);
    return WhenVisible(
      builder: (context, visible) {
        if (visible && !_c.isAnimating && _c.value == 0) {
          reduce ? _c.value = 1 : _c.forward();
          // Phones show the newest weeks first.
          WidgetsBinding.instance.addPostFrameCallback((_) {
            if (_scroll.hasClients) {
              _scroll.jumpTo(_scroll.position.maxScrollExtent);
            }
          });
        }
        return LayoutBuilder(
          builder: (context, box) {
            const labelW = 34.0;
            final cell = ((box.maxWidth - labelW) / _weeks - _gap).clamp(
              11.0,
              20.0,
            );
            final gridW = _weeks * (cell + _gap);
            final h = 7 * (cell + _gap);
            final grid = SizedBox(
              width: gridW,
              height: h + 24,
              child: Stack(
                clipBehavior: Clip.none,
                children: [
                  for (var m = 0; m < _weeks; m++)
                    if (_monthStart(m))
                      Positioned(
                        left: m * (cell + _gap),
                        top: 0,
                        child: Text(
                          _month(_date(m * 7)),
                          style: SLType.label(SLColors.inkMuted),
                        ),
                      ),
                  Positioned(
                    top: 24,
                    left: 0,
                    child: MouseRegion(
                      onExit: (_) => setState(() => _hover = null),
                      onHover: (e) {
                        final w = (e.localPosition.dx / (cell + _gap)).floor();
                        final d = (e.localPosition.dy / (cell + _gap)).floor();
                        final i = w * 7 + d;
                        final ok =
                            w >= 0 &&
                            w < _weeks &&
                            d >= 0 &&
                            d < 7 &&
                            _shown(i);
                        if ((ok ? i : null) != _hover) {
                          setState(() => _hover = ok ? i : null);
                        }
                      },
                      child: AnimatedBuilder(
                        animation: _c,
                        builder: (context, _) => CustomPaint(
                          size: Size(gridW, h),
                          painter: _GridPainter(
                            cell: cell,
                            t: _c.value,
                            hover: _hover,
                            shown: _shown,
                            count: (i) => commitDays[_key(_date(i))] ?? 0,
                          ),
                        ),
                      ),
                    ),
                  ),
                  if (_hover != null) _tooltip(_hover!, cell),
                ],
              ),
            );
            return Row(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                SizedBox(
                  width: labelW,
                  child: Padding(
                    padding: const EdgeInsets.only(top: 24),
                    child: Column(
                      crossAxisAlignment: CrossAxisAlignment.start,
                      children: [
                        for (final d in ['', 'Mon', '', 'Wed', '', 'Fri', ''])
                          SizedBox(
                            height: cell + _gap,
                            child: Text(
                              d,
                              style: SLType.label(
                                SLColors.inkMuted,
                              ).copyWith(fontSize: 10, letterSpacing: 0),
                            ),
                          ),
                      ],
                    ),
                  ),
                ),
                Expanded(
                  child: Column(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [
                      SingleChildScrollView(
                        controller: _scroll,
                        scrollDirection: Axis.horizontal,
                        child: grid,
                      ),
                      const SizedBox(height: 12),
                      const _Legend(),
                    ],
                  ),
                ),
              ],
            );
          },
        );
      },
    );
  }

  bool _shown(int i) => !_date(i).isAfter(DateTime.now());

  bool _monthStart(int w) =>
      w == 0 || _date(w * 7).month != _date((w - 1) * 7).month;

  static const _months = [
    'Jan',
    'Feb',
    'Mar',
    'Apr',
    'May',
    'Jun',
    'Jul',
    'Aug',
    'Sep',
    'Oct',
    'Nov',
    'Dec',
  ];
  String _month(DateTime d) => _months[d.month - 1];

  Widget _tooltip(int i, double cell) {
    final d = _date(i);
    final n = commitDays[_key(d)] ?? 0;
    final x = (i ~/ 7) * (cell + _gap);
    final y = 24 + (i % 7) * (cell + _gap);
    return Positioned(
      left: (x - 44).clamp(0.0, double.infinity),
      top: y - 38,
      child: IgnorePointer(
        child: Container(
          padding: const EdgeInsets.symmetric(horizontal: 10, vertical: 6),
          decoration: BoxDecoration(
            color: SLColors.surface,
            border: Border.all(color: SLColors.hairline),
          ),
          child: Text(
            '${n == 0 ? 'No commits' : '$n commit${n == 1 ? '' : 's'}'}  ·  ${_month(d)} ${d.day}',
            style: SLType.label(SLColors.ink),
          ),
        ),
      ),
    );
  }
}

Color _levelColor(int n) {
  if (n == 0) return Colors.white.withValues(alpha: 0.06);
  final level = n >= 8
      ? 4
      : n >= 4
      ? 3
      : n >= 2
      ? 2
      : 1;
  return Color.lerp(
    const Color(0xFF5A3F0A),
    SLColors.accentHover,
    (level - 1) / 3,
  )!;
}

class _GridPainter extends CustomPainter {
  final double cell, t;
  final int? hover;
  final bool Function(int) shown;
  final int Function(int) count;
  _GridPainter({
    required this.cell,
    required this.t,
    required this.hover,
    required this.shown,
    required this.count,
  });

  @override
  void paint(Canvas canvas, Size size) {
    for (var w = 0; w < _weeks; w++) {
      for (var d = 0; d < 7; d++) {
        final i = w * 7 + d;
        if (!shown(i)) continue;
        // A wave crossing left to right, each square catching a beat after
        // its neighbour; the busiest days flare as they land.
        final start = (w + d * 0.35) / (_weeks + 3);
        final p = const Cubic(
          0.16,
          1,
          0.3,
          1,
        ).transform(((t * 1.5 - start * 1.0) / 0.5).clamp(0.0, 1.0));
        if (p <= 0) continue;
        final n = count(i);
        final c = _levelColor(n);
        final s = cell * (0.3 + 0.7 * p);
        final o = Offset(
          w * (cell + _gap) + (cell - s) / 2,
          d * (cell + _gap) + (cell - s) / 2,
        );
        final r = RRect.fromRectAndRadius(
          Rect.fromLTWH(o.dx, o.dy, s, s),
          Radius.circular(cell * 0.2),
        );
        if (n >= 4) {
          canvas.drawRRect(
            r,
            Paint()
              ..color = SLColors.accent.withValues(alpha: 0.35 * p)
              ..maskFilter = const MaskFilter.blur(BlurStyle.normal, 4),
          );
        }
        canvas.drawRRect(r, Paint()..color = c.withValues(alpha: c.a * p));
        if (hover == i) {
          canvas.drawRRect(
            r.inflate(1.5),
            Paint()
              ..style = PaintingStyle.stroke
              ..strokeWidth = 1.5
              ..color = SLColors.ink,
          );
        }
      }
    }
  }

  @override
  bool shouldRepaint(_GridPainter old) => old.t != t || old.hover != hover;
}

