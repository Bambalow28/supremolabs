DateTime _day(String key) => DateTime.parse(key);

String _key(DateTime d) =>
    '${d.year}-${d.month.toString().padLeft(2, '0')}-${d.day.toString().padLeft(2, '0')}';

/// Totals read straight off the generated git history.
({int commits, int days, int streak, int best}) _totals() {
  final keys = commitDays.keys.toList()..sort();
  var streak = 0, run = 0, best = 0;
  DateTime? prev;
  for (final k in keys) {
    final d = _day(k);
    run = prev != null && d.difference(prev).inDays == 1 ? run + 1 : 1;
    if (run > streak) streak = run;
    if (commitDays[k]! > best) best = commitDays[k]!;
    prev = d;
  }
  return (
    commits: commitDays.values.fold(0, (a, b) => a + b),
    days: keys.length,
    streak: streak,
    best: best,
  );
}

